"""SPP-87 Card A probe: reconcile SPP's EIA-923 coal/gas benchmark against EIA-930 and CEMS (zero LP).

Reads only committed / on-disk inputs, never solves:

* keeper payload + bench parts via ``calibration_verdict.load_artifacts`` (the scorer's own loader);
* the keeper's EIA-923 benchmark frame ``results/calibration/_shared/SPP/eia923-d4ff957f221a.parquet``
  (gitignored shared input, regenerated by any SPP solve; named in the keeper's ``meta.json``);
* ``data/raw/eia-923-generation-fuel``, ``data/raw/eia-860/eia860_plant.parquet``;
* ``data/raw/campd-unit-level/<ST>_<Y>.parquet`` (CEMS gross, coal units of the scorer's coal plants);
* ``data/raw/SWPP_fueltype.parquet`` (EIA-930) and ``data/raw/spp-genmix/GenMix_<Y>.csv`` (SPP portal).

Writes ``results/calibration/_spp87_benchmark_reconcile.json``:

* ``coal_gap`` — per year, EIA-930 coal minus the scorer's ``classFull`` coal, split into
  station service (CEMS gross − EIA-923 net, same plants), the combined-fossil reconcile scale,
  SPP's own reporting residual (930 − CEMS gross) and BA membership;
* ``hourly_fit`` — OLS of hourly EIA-930 coal on hourly CEMS gross (slope ≈ 1 ⇒ gross basis,
  ≈ 0.92 ⇒ net basis);
* ``model_vs`` — keeper model minus each benchmark, coal / gas / wind;
* ``shadow`` — C1/C2 row status under the committed bench, a NET basis (reconcile scale undone)
  and a GROSS-coal basis (per-plant CEMS gross routed to the plant's coal class). Diagnostic only;
  nothing here changes the scorer.

Run: ``uv run python scripts/probes/_spp87_benchmark_reconcile.py`` (~3 min, CEMS reads dominate).
"""

from __future__ import annotations

import copy
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "scripts"))
import calibration_verdict as cv  # noqa: E402

RUN_ID = "2026-09-26-spp-86-coal-extract"
FRAME = REPO / "results/calibration/_shared/SPP/eia923-d4ff957f221a.parquet"
OUT = REPO / "results/calibration/_spp87_benchmark_reconcile.json"
YEARS = range(2019, 2026)
COAL_FUELS = {"BIT", "SUB", "LIG", "RC", "WC"}
COAL = ("COAL_PRB", "COAL_LIGNITE", "COAL_BIT")
GAS = ("CC_REGULAR", "CC_CHP", "CT_PEAKER", "CT_CHP", "ST_GAS", "ST_CHP", "OTHER_FOSSIL")
# States any SPP-footprint coal plant sits in (CAMPD files are per state).
STATES = ("KS", "OK", "NE", "MO", "AR", "TX", "LA", "NM", "ND", "SD", "MT", "WY", "IA", "MN")


def cems_coal(year: int, ids: set[int]) -> pd.DataFrame:
    """Hourly CEMS gross MWh (grossLoad × opTime) of coal units at ``ids``, CAMPD local standard time."""
    frames = []
    for st in STATES:
        f = REPO / f"data/raw/campd-unit-level/{st}_{year}.parquet"
        if not f.exists():
            continue
        d = pd.read_parquet(
            f, columns=["facilityId", "date", "hour", "opTime", "grossLoad", "primaryFuelInfo"]
        )
        d["facilityId"] = pd.to_numeric(d["facilityId"], errors="coerce")
        frames.append(d[d.facilityId.isin(ids) & (d.primaryFuelInfo == "Coal")])
    c = pd.concat(frames)
    c["mwh"] = c.grossLoad.fillna(0.0) * c.opTime.fillna(0.0)
    c["ts"] = c["date"] + pd.to_timedelta(c["hour"], unit="h")
    return c[["facilityId", "ts", "mwh"]]


def portal_twh(year: int) -> dict[str, float]:
    """SPP portal gen-mix annual TWh by fuel (5-min MW → hourly mean → annualised)."""
    df = pd.read_csv(REPO / f"data/raw/spp-genmix/GenMix_{year}.csv")
    df.columns = [c.strip() for c in df.columns]
    t = pd.to_datetime(df.iloc[:, 0], utc=True)
    keep = t.dt.tz_convert("America/Chicago").dt.year == year
    df, t = df[keep], t[keep]
    df.index = t.dt.floor("h")
    h = df.iloc[:, 1:].groupby(level=0).mean()
    hours = 8784 if year % 4 == 0 else 8760
    scale = hours / len(h) / 1e6

    def fuel(*prefixes: str) -> float:
        cols = [c for c in h.columns if c.lower().startswith(prefixes)]
        return float(h[cols].sum(axis=1).sum() * scale)

    return {
        "coal": fuel("coal"),
        "gas": fuel("natural gas", "gas self"),
        "wind": fuel("wind"),
    }


def shadow_bench(year: int, bench: dict, frame: pd.DataFrame, plant: pd.DataFrame, gross: bool):
    """Return (bench copy with the fossil reconcile scale undone [+ gross coal], scale factor)."""
    b = copy.deepcopy(bench)
    cf = b["classFull"]
    fy = frame[(frame.year == year) & frame.klass.isin(COAL)]
    k = cf["COAL_PRB"] / (fy[fy.klass == "COAL_PRB"].annual_mwh.sum() / 1e6)
    for c in (*COAL, *GAS):
        if c in cf:
            cf[c] = cf[c] / k
    if gross:
        fr = fy.groupby(["plant_id", "klass"]).annual_mwh.sum().reset_index()
        p = plant[plant.year == year].set_index("plant_id")
        ratio = (p.gross / p.net923).where((p.gross > 0) & (p.net923 > 0), 1.0)
        fr["g"] = fr.annual_mwh * fr.plant_id.map(ratio).fillna(1.0)
        for c, v in (fr.groupby("klass").g.sum() / 1e6).items():
            cf[c] = float(v)
    return b, float(k)


def main() -> None:
    """Build every table and write the JSON record."""
    art = cv.load_artifacts(RUN_ID)
    pay = art["payload"]["years"]
    bench = art["bench"]
    frame = pd.read_parquet(FRAME)
    e923 = pd.read_csv(REPO / "data/raw/eia-923-generation-fuel/eia923_generation_fuel_2019_2025.csv")
    p860 = pd.read_parquet(REPO / "data/raw/eia-860/eia860_plant.parquet")[
        ["Plant Code", "Plant Name", "Balancing Authority Code"]
    ]
    p860.columns = ["plant_id", "name", "ba"]
    p860["plant_id"] = pd.to_numeric(p860.plant_id, errors="coerce")
    e930 = pd.read_parquet(REPO / "data/raw/SWPP_fueltype.parquet")
    e930 = e930[e930.fueltype == "COL"].copy()
    e930["year"] = e930.period.dt.tz_convert("America/Chicago").dt.year
    # EIA-930 hour-ending UTC → CAMPD local-standard hour-beginning.
    e930["ts"] = e930.period.dt.tz_convert("Etc/GMT+6").dt.tz_localize(None) - pd.Timedelta(hours=1)

    coal923 = e923[e923.fuel_type.isin(COAL_FUELS)].merge(p860, on="plant_id", how="left")
    rec: dict = {"run_id": RUN_ID, "coal_gap": {}, "hourly_fit": {}, "model_vs": {}, "shadow": []}
    plant_rows = []
    for y in YEARS:
        ids = set(frame[(frame.year == y) & frame.klass.isin(COAL)].plant_id.astype(int))
        c = cems_coal(y, ids)
        gross_p = c.groupby("facilityId").mwh.sum() / 1e6
        net_p = coal923[(coal923.year == y) & coal923.plant_id.isin(ids)].groupby("plant_id").net_generation_mwh.sum() / 1e6
        pp = pd.DataFrame({"gross": gross_p, "net923": net_p}).fillna(0.0)
        pp.index.name = "plant_id"
        plant_rows.append(pp.reset_index().assign(year=y))
        metered = pp[pp.gross > 0]
        unmetered_net = float(pp[pp.gross == 0].net923.sum())
        cf = bench[y]["classFull"]
        cf_coal = sum(cf.get(k, 0.0) for k in COAL)
        frame_coal = frame[(frame.year == y) & frame.klass.isin(COAL)].annual_mwh.sum() / 1e6
        e930_coal = float(bench[y]["e930"]["coal"])
        gross_all = float(metered.gross.sum()) + unmetered_net
        sw = coal923[(coal923.year == y) & (coal923.ba == "SWPP")]
        outside = float(sw[~sw.plant_id.isin(ids)].net_generation_mwh.sum() / 1e6)
        rec["coal_gap"][y] = {
            "e930_coal": round(e930_coal, 3),
            "portal_coal": round(portal_twh(y)["coal"], 3),
            "classFull_coal": round(cf_coal, 3),
            "frame_coal_net923": round(float(frame_coal), 3),
            "cems_gross_plus_unmetered": round(gross_all, 3),
            "gap_930_minus_classFull": round(e930_coal - cf_coal, 3),
            "of_which_reconcile_scale": round(cf_coal - float(frame_coal), 3),
            "of_which_station_service": round(float(metered.gross.sum() - metered.net923.sum()), 3),
            "of_which_spp_reporting_residual": round(e930_coal - gross_all, 3),
            "swpp_ba_coal_outside_scorer_set": round(outside, 3),
            "net_over_gross_metered": round(float(metered.net923.sum() / metered.gross.sum()), 4),
        }
        h = c.groupby("ts").mwh.sum()
        s = e930[e930.year == y].set_index("ts").value_mwh
        j = pd.concat({"g": h, "e": s}, axis=1, sort=True).dropna()
        a, b0 = np.linalg.lstsq(np.vstack([j.g, np.ones(len(j))]).T, j.e, rcond=None)[0]
        rec["hourly_fit"][y] = {
            "n": int(len(j)),
            "corr": round(float(j.g.corr(j.e)), 4),
            "slope": round(float(a), 4),
            "intercept_mw": round(float(b0), 1),
            "median_ratio_930_over_gross": round(float((j.e / j.g).median()), 4),
        }
        gm = pay[str(y)]["gmModel"]
        m_coal = sum(gm.get(k, 0.0) for k in COAL)
        m_gas = sum(gm.get(k, 0.0) for k in GAS)
        rec["model_vs"][y] = {
            "coal_vs_923": round(m_coal - cf_coal, 3),
            "coal_vs_gross": round(m_coal - gross_all, 3),
            "coal_vs_930": round(m_coal - e930_coal, 3),
            "gas_vs_923": round(m_gas - sum(cf.get(k, 0.0) for k in GAS), 3),
            "gas_vs_930": round(m_gas - float(bench[y]["e930"]["gas"]), 3),
            "wind_vs_930": round(gm.get("wind", 0.0) - float(bench[y]["e930"]["wind"]), 3),
        }
    plant = pd.concat(plant_rows)

    net_all = {y: shadow_bench(y, bench[y], frame, plant, False)[0] for y in bench}
    gross_all_b = {y: shadow_bench(y, bench[y], frame, plant, True)[0] for y in bench}

    def rows(y: int, b: dict, ball: dict) -> dict:
        out = cv.score_fuelmix(y, pay[str(y)], b, iso="SPP") + cv.score_sysvol(
            y, pay[str(y)], b, iso="SPP", bench_all=ball
        )
        return {(r["criterion"], r.get("key")): r for r in out}

    for y in YEARS:
        base = rows(y, bench[y], bench)
        net = rows(y, net_all[y], net_all)
        grs = rows(y, gross_all_b[y], gross_all_b)
        k = shadow_bench(y, bench[y], frame, plant, False)[1]
        for key, r in base.items():
            rec["shadow"].append(
                {
                    "year": y,
                    "criterion": key[0],
                    "key": key[1],
                    "reconcile_scale": round(k, 4),
                    "model": r.get("model"),
                    "committed_actual": r.get("actual"),
                    "committed": r["status"],
                    "net_actual": net[key].get("actual"),
                    "net": net[key]["status"],
                    "gross_actual": grs[key].get("actual"),
                    "gross": grs[key]["status"],
                }
            )
    OUT.write_text(json.dumps(rec, indent=1, default=str))
    moved = [s for s in rec["shadow"] if len({s["committed"], s["net"], s["gross"]}) > 1]
    print(json.dumps({"coal_gap": rec["coal_gap"], "hourly_fit": rec["hourly_fit"]}, indent=1))
    print("status moves:", json.dumps(moved, indent=1))


if __name__ == "__main__":
    main()
