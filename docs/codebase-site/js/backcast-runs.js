    /* Plants of a class in the selected zones. */
    function plantsOf(yr, grp) {
      const M = RUN(yr), B = BENCH(yr);
      if (!M?.plants || !B?.plants) return [];
      return Object.keys(M.plants).filter(c => {
        const b = B.plants[c];
        return b && b.group === grp && st.zones.has(b.zone);
      });
    }

    /* Aggregate model vs CAMPD MW arrays for a class + selected zones. */
    const _aggC = {};
    function clearAggCache() {
      Object.keys(_aggC).forEach(k => delete _aggC[k]);
      Object.keys(_matchC).forEach(k => delete _matchC[k]);
    }
    function aggMW(yr, grp) {
      const key = st.runId + '|' + yr + '|' + grp + '|' + [...st.zones].sort().join(',');
      if (_aggC[key]) return _aggC[key];
      const M = RUN(yr), B = BENCH(yr);
      const mm = new Float32Array(T), cc = new Float32Array(T);
      let mA = 0, cA = 0, eA = 0;
      for (const c of plantsOf(yr, grp)) {
        const b = B.plants[c], mp = M.plants[c];
        const npl = b.npl || 1;
        if (mp?.m) { const md = dec(mp.m); for (let i = 0; i < T; i++) mm[i] += md[i] * npl / 100; }
        if (b?.campd) { const cd = dec(b.campd); for (let i = 0; i < T; i++) cc[i] += cd[i] * npl / 100; }
        mA += mp?.m_ann || 0;
        cA += b?.c_ann || 0;
        eA += b?.e_ann || 0;
      }
      return _aggC[key] = { mm, cc, mA, cA, eA };
    }

    /* CAMPD-MATCHED class aggregate — the apples-to-apples pair for the delta map.
       aggMW() sums the model over EVERY plant of the class in the selected zones,
       but the CAMPD side can only sum the plants CEMS actually files a usable
       hourly record for: a plant with no CEMS series (`nodata`) contributes model
       MW against a flat zero, and a CT-only reporter contributes model MW for the
       full 2x1 block against a CAMPD series covering only its combustion turbines.
       Differencing those two totals reports a dispatch error that is really a
       reporting-coverage gap. This sums BOTH sides over the intersection only —
       plants present in the model run AND carrying a complete CAMPD record — and
       returns the matched nameplate (`capMW`) that normalizes the delta, plus the
       full-class counts so the panel can name what it dropped. */
    const _matchC = {};
    function matchedAggMW(yr, grp) {
      const key = st.runId + '|' + yr + '|' + grp + '|' + [...st.zones].sort().join(',');
      if (_matchC[key]) return _matchC[key];
      const M = RUN(yr), B = BENCH(yr);
      const all = plantsOf(yr, grp);
      const mm = new Float32Array(T), cc = new Float32Array(T);
      let capMW = 0, capAll = 0, n = 0;
      for (const c of all) {
        const b = B.plants[c], mp = M.plants[c];
        const npl = b.npl || 1;
        capAll += npl;
        if (!b.campd || b.nodata || b.ct_only || !mp?.m) continue;
        n++; capMW += npl;
        const md = dec(mp.m), cd = dec(b.campd);
        for (let i = 0; i < T; i++) { mm[i] += md[i] * npl / 100; cc[i] += cd[i] * npl / 100; }
      }
      return _matchC[key] = { mm, cc, capMW, capAll, n, nAll: all.length };
    }

    /* Full EIA-923 class total (classFull from benchmark), zone-allocated. */
    function classBench923(yr, grp, eAzones) {
      const B = BENCH(yr);
      const cf = B.classFull?.[grp], plants = B.plants || {};
      let eAll = 0;
      for (const c in plants) { if (plants[c].group === grp) eAll += plants[c].e_ann || 0; }
      return (cf != null && eAll > 0) ? cf * (eAzones / eAll) : eAzones;
    }

    /* Full model class total (gmModel), zone-allocated. */
    function classModelFull(yr, grp, mAzones) {
      const M = RUN(yr), B = BENCH(yr);
      const gm = M.gmModel?.[grp];
      let mAll = 0;
      for (const c in (M.plants || {})) {
        if (B.plants?.[c]?.group === grp) mAll += M.plants[c].m_ann || 0;
      }
      return (gm != null && mAll > 0) ? gm * (mAzones / mAll) : mAzones;
    }

    /* Class metrics — the port of the retired shell's classMetrics, and now its
       only implementation:
       r (Pearson), nr (MEAN-normalized NRMSE, model vs CAMPD), dev (volume
       deviation), m1 (composite capture score = "Class capture" KPI), m2
       (npl-weighted mean of per-plant .cap = "Plant capture" KPI), plus the
       zone-allocated model/EIA-923 class totals. */
    function classMetrics(yr, grp) {
      const ps = plantsOf(yr, grp);
      if (!ps.length) return null;
      const a = aggMW(yr, grp);
      const r = pearson(a.mm, a.cc), nr = nrmseM(a.mm, a.cc), dev = a.cA > 0 ? (a.mA - a.cA) / a.cA : 0;
      const m1 = a.cc.reduce((s, v) => s + v, 0) > 0 ? capScore(r, nr, dev) : null;
      const M = RUN(yr), B = BENCH(yr);
      let ws = 0, cs = 0;
      for (const c of ps) { const w = B.plants[c].npl, cp = M.plants[c].cap; if (cp != null) { ws += w; cs += w * cp; } }
      return {
        m1, m2: ws > 0 ? cs / ws : null, r, nr, dev,
        mA: a.mA, cA: a.cA, eA: a.eA,
        mFull: classModelFull(yr, grp, a.mA),
        bench923: classBench923(yr, grp, a.eA),
        n: ps.length
      };
    }

    /* Single-plant or aggregate series for Charts view — mirrors the shell
       singleSeries: a single plant carries the payload's Python-computed
       r/nrmse/cap (never recomputed in JS); the aggregate carries the class
       mt.r/mt.nr and grid-delivered mFull/bench923 volume totals. */
    function singleSeries(yr, grp, plantCode) {
      if (isNF(grp)) return nfSeries(yr, grp);
      const M = RUN(yr), B = BENCH(yr);
      const ps = plantsOf(yr, grp);
      if (plantCode && plantCode !== 'agg' && B.plants?.[plantCode] && M.plants?.[plantCode]) {
        const b = B.plants[plantCode], mp = M.plants[plantCode];
        const npl = b.npl || 1;
        const mm = new Float32Array(T), cc = new Float32Array(T);
        if (mp?.m) { const md = dec(mp.m); for (let i = 0; i < T; i++) mm[i] = md[i] * npl / 100; }
        if (b?.campd) { const cd = dec(b.campd); for (let i = 0; i < T; i++) cc[i] = cd[i] * npl / 100; }
        const nodata = !!b.nodata || !b.campd || cc.every(v => v === 0);
        return {
          name: (b.name || plantCode) + ' · ' + (b.zone || '?'), agg: false, nodata,
          ctOnly: !!b.ct_only, ctRatio: b.ct_ratio ?? null,
          mm, cc, m_ann: mp.m_ann || 0, c_ann: b.c_ann || 0, e_ann: b.e_ann || 0,
          r: mp.r ?? null, nr: mp.nrmse ?? null, cap: mp.cap ?? null
        };
      }
      const a = aggMW(yr, grp);
      const mt = classMetrics(yr, grp);
      const nodata = a.cA <= 0;
      return {
        name: (META().groupLabel?.[grp] || grp) + ' (aggregate)', agg: true, nodata,
        mm: a.mm, cc: a.cc,
        m_ann: mt ? mt.mFull : a.mA, c_ann: a.cA, e_ann: (mt && mt.bench923 > 0) ? mt.bench923 : a.eA,
        r: mt ? mt.r : null, nr: mt ? mt.nr : null, cap: mt ? mt.m1 : null
      };
    }

    /* Non-fossil / imports series in the SAME shape singleSeries returns for a
       fossil class, so every downstream chart consumes it unchanged. Model
       (`mm`) and EIA-930 actual (`cc`) are both MW, decoded over the panel's
       SHARED [lo, hi] window — that is what makes mm - cc a true MW delta.
       r/nrmse come from the payload (Python-computed; the frontend never
       recomputes class fit, matching the existing contract). `nodata` marks a
       bucket the BA files no series for (payload `a: null` — e.g. NYISO solar),
       which suppresses the actual map and the delta map exactly as a missing
       CAMPD record does for a fossil plant. */
    function nfSeries(yr, grp) {
      const key = nfKey(grp);
      const e = nfPanels(yr)[key];
      const mm = new Float32Array(T), cc = new Float32Array(T);
      if (!e) {
        return {
          name: grpLabel(grp), agg: true, nodata: true, nonfossil: true,
          mm, cc, m_ann: 0, c_ann: 0, e_ann: 0, r: null, nr: null, cap: null,
          src: 'EIA-930', classes: [],
          note: `This run carries no ${grpLabel(grp)} hourly panel for ${yr}.`
        };
      }
      const m = decAffine(e.m, e.lo, e.hi);
      for (let i = 0, n = Math.min(T, m.length); i < n; i++) mm[i] = m[i];
      if (e.a) {
        const a = decAffine(e.a, e.lo, e.hi);
        for (let i = 0, n = Math.min(T, a.length); i < n; i++) cc[i] = a[i];
      }
      return {
        name: (e.label || key) + ' · ' + (SRC_LABEL[e.src] || e.src || 'EIA-930'),
        agg: true, nodata: !e.a, nonfossil: true,
        mm, cc,
        m_ann: e.mTwh ?? 0, c_ann: e.aTwh ?? 0, e_ann: e.aTwh ?? 0,
        r: e.r ?? null, nr: e.nrmse ?? null, nrBasis: e.nrmseBasis || null,
        cap: null, src: e.src || 'EIA-930', note: e.note || null,
        classes: e.classes || []
      };
    }

    /* Demand-weighted average LMP over selected zones. */
    function avgLMP(yr) {
      const L = RUN(yr).lmp || {};
      let pd = 0, d = 0;
      for (const z in L) {
        if (!st.zones.has(z)) continue;
        pd += (L[z].p || 0) * (L[z].d || 0);
        d += L[z].d || 0;
      }
      return d > 0 ? pd / d : null;
    }

    /* Monthly model LMP (demand-weighted across selected zones). */
    function avgLMPMon(yr) {
      const L = RUN(yr).lmp || {};
      const out = Array(12).fill(0);
      const dMon = Array(12).fill(0);
      let any = false;
      for (const z in L) {
        if (!st.zones.has(z)) continue;
        const zd = L[z];
        if (!zd.pMon || !zd.dMon) continue;
        any = true;
        for (let m = 0; m < 12; m++) {
          if (zd.pMon[m] == null) continue;
          out[m] += zd.pMon[m] * (zd.dMon[m] || 0);
          dMon[m] += zd.dMon[m] || 0;
        }
      }
      if (!any) return null;
      return out.map((s, m) => dMon[m] > 0 ? s / dMon[m] : null);
    }

    /* ORDC-overlaid monthly LMP. */
    function avgLMPMonScar(yr) {
      const Y = RUN(yr), S = Y.lmpScar, L = Y.lmp || {};
      if (!S) return null;
      const out = Array(12).fill(0), dMon = Array(12).fill(0);
      let any = false;
      for (const z in S) {
        if (!st.zones.has(z)) continue;
        const sp = S[z].pMonScar, dm = (L[z] || {}).dMon;
        if (!sp || !dm) continue;
        any = true;
        for (let m = 0; m < 12; m++) {
          if (sp[m] == null) continue;
          out[m] += sp[m] * dm[m];
          dMon[m] += dm[m] || 0;
        }
      }
      if (!any) return null;
      return out.map((s, m) => dMon[m] > 0 ? s / dMon[m] : null);
    }

    /* Annual demand-weighted ORDC-overlaid avg LMP. */
    function avgLMPScar(yr) {
      const ms = avgLMPMonScar(yr);
      if (!ms) return null;
      const L = RUN(yr).lmp || {};
      const dT = Array(12).fill(0);
      for (const z in L) { if (!st.zones.has(z)) continue; const dm = L[z].dMon; if (dm) for (let m = 0; m < 12; m++) dT[m] += dm[m] || 0; }
      let pd = 0, d = 0;
      for (let m = 0; m < 12; m++) { if (ms[m] != null) { pd += ms[m] * dT[m]; d += dT[m]; } }
      return d > 0 ? pd / d : null;
    }

    function actualLMP(yr) { return BENCH(yr).avgLMP || null; }
    /* Gated actual-price basis — mirrors calibration_verdict.score_price_mean's
       ladder (rt_lw > da_lw > rt > da). A perfect-foresight dispatch LP is a
       real-time analogue (it prices RT physics, not day-ahead risk premia), so
       RT is the honest benchmark the Calibration Status page gates on; DA is
       only a fallback when no RT actual is committed. Returns the annual mean,
       its basis label, and whether it is the load-weighted series. */
    function actualLMPGated(yr) {
      const a = actualLMP(yr);
      if (!a) return null;
      if (a.rt_lw != null) return { val: a.rt_lw, basis: 'RT', lw: true };
      if (a.da_lw != null) return { val: a.da_lw, basis: 'DA', lw: true };
      if (a.rt != null) return { val: a.rt, basis: 'RT', lw: false };
      if (a.da != null) return { val: a.da, basis: 'DA', lw: false };
      return null;
    }
