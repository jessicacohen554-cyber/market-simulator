    /* System totals. */
    function totalGen(yr) {
      const B = BENCH(yr), M = RUN(yr);
      if (!B?.classFull) return null;
      const gm = M.gmModel || {};
      const aGen = Object.values(B.classFull).reduce((s, v) => s + (v || 0), 0);
      const mGen = Object.keys(B.classFull).reduce((s, g) => s + (gm[g] || 0), 0);
      return (mGen > 0 && aGen > 0) ? { mGen, aGen } : null;
    }
    function totalLoad(yr) {
      const L = RUN(yr).lmp || {};
      const s = Object.values(L).reduce((a, z) => a + (z.d || 0), 0);
      return s > 0 ? s : (totalGen(yr)?.aGen || 0);
    }
    function sharePP(yr, mCls, aCls) {
      const T = totalGen(yr); if (!T) return null;
      return 100 * mCls / T.mGen - 100 * aCls / T.aGen;
    }

    /* Class error objects (fossil + non-fossil). */
    function classErr(yr, grp) {
      const m = classMetrics(yr, grp);
      const mSys = RUN(yr).gmModel?.[grp] || 0;
      const aSys = BENCH(yr).classFull?.[grp] || 0;
      if (!m) {
        // No CAMPD-matched plants for this class (e.g. ERCOT ST_CHP) — fall
        // back to the system-wide gmModel/classFull totals the verdict gates
        // on, so the C1 count spans the same classes as Calibration Status.
        if (!(aSys > 0.02)) return null;
        return {
          grp, err: 100 * (mSys - aSys) / aSys, mFull: mSys, bench923: aSys,
          annLoad: totalLoad(yr), aGen: totalGen(yr)?.aGen || 0,
          sharePP: sharePP(yr, mSys, aSys), r: null, nr: null
        };
      }
      if (!(m.bench923 > 0.02)) return null;
      return {
        grp, err: 100 * (m.mFull - m.bench923) / m.bench923,
        mFull: m.mFull, bench923: m.bench923,
        annLoad: totalLoad(yr), aGen: totalGen(yr)?.aGen || 0,
        sharePP: sharePP(yr, mSys, aSys), r: m.r, nr: m.nr
      };
    }
    function nonFosErr(yr, fuel) {
      const a = BENCH(yr).e930?.[fuel] || 0, m = RUN(yr).nonfossil?.[fuel] || 0;
      if (!(a > 0.02)) return null;
      return {
        grp: fuel, nonfos: true, err: 100 * (m - a) / a,
        mFull: m, bench923: a, annLoad: totalLoad(yr),
        aGen: totalGen(yr)?.aGen || 0, sharePP: sharePP(yr, m, a)
      };
    }
    function anyErr(yr, g) { return NONFOSSIL.includes(g) ? nonFosErr(yr, g) : classErr(yr, g); }
    function allClasses() { return [...(META().groups || []), ...NONFOSSIL]; }
    function classLabel(g) {
      if (NONFOSSIL.includes(g)) return g[0].toUpperCase() + g.slice(1);
      return META().groupLabel?.[g] || g;
    }

    /* Tolerance. Volume band = min(max(2% load, 3% actual gen), 8 TWh) —
       the gen-floor is the rubric v3.4 owner amendment (2026-08-18), mirrors
       calibration_verdict._fuelmix_vol_band. */
    function volInTol(e, k) { return e.annLoad > 0 && Math.abs(e.mFull - e.bench923) <= k * Math.min(Math.max(SUM_TOL_LOAD_FRAC * e.annLoad, SUM_TOL_GEN_FLOOR_FRAC * (e.aGen || 0)), SUM_TOL_LOAD_CAP); }
    function shareInTol(e, k) { return e.sharePP == null || Math.abs(e.sharePP) <= k * SUM_TOL_SHARE_PP; }
    function classInTol(e) { return volInTol(e, 1) && shareInTol(e, 1); }
    function clsTol(e) { return classInTol(e) ? 'good' : (volInTol(e, 2) && shareInTol(e, 2)) ? 'ok' : 'bad'; }
    function tolcls(v) { const a = Math.abs(v); return a <= SUM_TOL_PCT ? 'clr-good' : a <= 2 * SUM_TOL_PCT ? 'clr-ok' : 'clr-bad'; }
    /* Whether a class GATES in the C1 fuel-mix test for this year — mirrors
       calibration_verdict.score_fuelmix + class_is_gated: gas/coal family
       membership, not FUELMIX_EXCLUDED, and (in a preliminary-EIA-923 vintage)
       verified complete by the committed completeness audit. Everything else on
       the page is report-only context, exactly like the verdict. */
    function classIsGated(yr, g) {
      if (!GAS_CLASSES.includes(g) && !COAL_CLASSES.includes(g)) return false;
      if (FUELMIX_EXCLUDED.has(g)) return false;
      const ci = cmpInfo(yr, st.iso, g);
      return !ci || !!ci.gate; // no completeness part = complete vintage -> gates
    }

    function classErrs(yr) {
      const out = [];
      for (const g of allClasses()) { const e = anyErr(yr, g); if (e) out.push(e); }
      return out;
    }

    /* Generation-weighted fleet dispatch r. */
    function fleetR(yr) {
      let ws = 0, s = 0;
      for (const g of (META().groups || [])) {
        const m = classMetrics(yr, g);
        if (!m || m.cA <= 0) continue;
        ws += m.cA; s += m.cA * m.r;
      }
      return ws > 0 ? s / ws : null;
    }

    /* Summary headline for a year. "Classes in tol" counts ONLY the C1-gated
       classes (the same set the Calibration Status verdict scores); classes a
       preliminary-vintage completeness audit skips are reported separately, and
       excluded/non-fossil classes never enter the count. Worst class is the
       largest error among the gated classes. */
    function summaryHeadline(yr) {
      const es = classErrs(yr);
      const gated = es.filter(e => classIsGated(yr, e.grp));
      const skipped = es.filter(e =>
        !FUELMIX_EXCLUDED.has(e.grp) && !NONFOSSIL.includes(e.grp)
        && (GAS_CLASSES.includes(e.grp) || COAL_CLASSES.includes(e.grp))
        && !classIsGated(yr, e.grp)).length;
      let worst = null;
      // Worst = out-of-tolerance first, then largest absolute TWh miss (the
      // C1 gate's own magnitude) — a tiny in-tolerance class with a big % error
      // (e.g. 0.4 TWh ST_CHP) must not outrank a 19 TWh CC miss.
      gated.forEach(e => {
        if (!worst) { worst = e; return; }
        const eOut = !classInTol(e), wOut = !classInTol(worst);
        if (eOut !== wOut) { if (eOut) worst = e; return; }
        if (Math.abs(e.mFull - e.bench923) > Math.abs(worst.mFull - worst.bench923)) worst = e;
      });
      return {
        n: gated.length, inTol: gated.filter(classInTol).length, skipped,
        worst, price: avgLMP(yr), priceScar: avgLMPScar(yr)
      };
    }

    /* ================================================================
       CF HEATMAP COLOR
       ================================================================ */
    function cfColorRGB(v) {
      if (v <= 1) return [232, 243, 247];
      const t = Math.min(v, 100) / 100;
      const S = [[0, 232, 243, 247], [0.04, 127, 196, 230], [0.30, 134, 201, 143],
                 [0.55, 242, 214, 92], [0.78, 239, 143, 60], [1, 192, 57, 43]];
      for (let i = 1; i < S.length; i++) {
        if (t <= S[i][0]) {
          const a = S[i - 1], b = S[i], f = (t - a[0]) / (b[0] - a[0]);
          return [a[1] + f * (b[1] - a[1]), a[2] + f * (b[2] - a[2]), a[3] + f * (b[3] - a[3])];
        }
      }
      return [192, 57, 43];
    }

    function drawHeat(cv, cf) {
      const ctx = cv.getContext('2d');
      const im = ctx.createImageData(365, 24);
      for (let h = 0; h < 8760; h++) {
        const day = h / 24 | 0, hod = h % 24;
        if (day > 364) break;
        const c = cfColorRGB(cf[h]);
        const i = (hod * 365 + day) * 4;
        im.data[i] = c[0]; im.data[i + 1] = c[1]; im.data[i + 2] = c[2]; im.data[i + 3] = 255;
      }
      ctx.putImageData(im, 0, 0);
    }

    /* ================================================================
       LMP DELTA HEATMAP — diverging color (model $/MWh minus actual)
       ================================================================ */
    // Diverging ramp: model OVER actual (positive delta) -> orange, model UNDER
    // (negative) -> blue, ~zero -> white. |delta| is normalized to ``cap`` and
    // gamma-shaped (<1) so small biases still read as tint — "show the
    // variation", not just the scarcity spikes. NaN (no data) -> neutral gray.
    const DELTA_ORANGE = [230, 126, 34];   // #E67E22 — model runs HOT
    const DELTA_BLUE = [33, 102, 172];     // #2166AC — model runs COLD
    const DELTA_NAN = [235, 238, 242];     // no model/actual price this hour
    function lmpDeltaColorRGB(d, cap) {
      if (d == null || isNaN(d)) return DELTA_NAN;
      const t = Math.max(-1, Math.min(1, d / (cap || 1)));
      const f = Math.pow(Math.abs(t), 0.7);
      const c = t >= 0 ? DELTA_ORANGE : DELTA_BLUE;
      return [255 + f * (c[0] - 255), 255 + f * (c[1] - 255), 255 + f * (c[2] - 255)];
    }

    function drawDeltaHeat(cv, arr, cap) {
      const ctx = cv.getContext('2d');
      const im = ctx.createImageData(365, 24);
      for (let h = 0; h < T; h++) {
        const day = h / 24 | 0, hod = h % 24;
        if (day > 364) break;
        const c = lmpDeltaColorRGB(arr[h], cap);
        const i = (hod * 365 + day) * 4;
        im.data[i] = c[0]; im.data[i + 1] = c[1]; im.data[i + 2] = c[2]; im.data[i + 3] = 255;
      }
      ctx.putImageData(im, 0, 0);
    }

    // Robust symmetric color cap = 98th percentile of |delta|, so a handful of
    // scarcity hours don't wash the whole map to one saturated tone. `min`/`step`
    // are the floor and rounding grain of the returned cap: the defaults (10, 5)
    // are the $/MWh grain the map was built with; a NORMALIZED (percent) series
    // passes a finer grain, because a 5-point floor on a 0-100 % scale would
    // flatten every sub-5 % map to a single tone.
    function deltaCap(arr, min = 10, step = 5) {
      const a = [];
      for (let i = 0; i < arr.length; i++) if (!isNaN(arr[i])) a.push(Math.abs(arr[i]));
      if (!a.length) return min;
      a.sort((x, y) => x - y);
      const p = a[Math.min(a.length - 1, Math.floor(a.length * 0.98))];
      return Math.max(min, Math.ceil(p / step) * step);
    }

    // Mean signed delta over finite hours (annual bias). Unit-agnostic — the
    // caller passes either the raw $/MWh series or its normalized percentage.
    function deltaMean(arr) {
      let s = 0, n = 0;
      for (let i = 0; i < arr.length; i++) if (!isNaN(arr[i])) { s += arr[i]; n++; }
      return n ? s / n : null;
    }

