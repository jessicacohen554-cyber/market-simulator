    // System-wide load (TWh): sum of every zone's annual demand in the payload —
    // the same reconciliation basis as the shell (model gen + net imports == load).
    function sysDemand(yr) { const L = RUN(yr).lmp || {}; let d = 0; for (const z in L) d += (L[z].d || 0); return d; }
    // EIA-923 completeness flag for one (year, iso, class) — drives the gen-mix
    // color code, matching the shell's cmpInfo/cmpBadge.
    function cmpInfo(yr, iso, g) { const C = getCompleteness()?.[yr]; if (!C) return null; return (C[iso] || {})[g] || { status: 'incomplete', gate: false }; }
    function cmpBadge(c) {
      if (!c) return '';
      if (c.status === 'complete') return ' <span class="badge-923 ok" title="EIA-923 verified complete — gates C1">&#10003; 923</span>';
      if (c.status === 'immaterial') return ' <span class="badge-923 imm" title="immaterial volume — not gated">&mdash; 923</span>';
      return ' <span class="badge-923 inc" title="incomplete EIA-923 plant data — not gated this vintage">&#9888; 923</span>';
    }

    // Generation mix + supply/load reconciliation — a faithful port of the shell
    // genMixPanel. Iterates over EVERY benchmarked class in classFull (fossil +
    // biomass/hydro/nuclear/oil/solar/wind, CHP listed separately), so shares
    // are share of TOTAL generation, and appends the net-imports / total-supply /
    // load rows so the net-import volume the generation-only rows omit is visible.
    function genMixTable(yr) {
      const B = BENCH(yr);
      if (!B || !B.classFull) return '';
      const cf = B.classFull, FG = Object.keys(cf), gm = RUN(yr).gmModel || {};
      const iso = st.iso;
      const aGen = FG.reduce((s, g) => s + (cf[g] || 0), 0);
      const mGen = FG.reduce((s, g) => s + (gm[g] || 0), 0);
      const prelim = !!getCompleteness()?.[yr];
      // Net imports (import-positive): the fuelRows "interchange" row is net-EXPORT
      // positive (EIA-930 sign), so flip it. Present only for a priced-interchange
      // bundle; a measured-schedule bundle nets interchange into demand (no row).
      const ix = (RUN(yr).fuelRows || []).find(x => x.fuel === 'interchange');
      const mImp = ix ? -ix.m : null, aImp = (ix && ix.b != null) ? -ix.b : null;
      const load = sysDemand(yr);

      // UNMERGED, on purpose: this table used to fold CHP into its parent
      // (CHP_MERGE), so the CC Regular row was CC_REGULAR + CC_CHP. That made
      // the row disagree with the class C1 actually gates — PJM 2023 read
      // -5.56 TWh merged while the gated CC_REGULAR was -8.10 against a ±8.00
      // band, i.e. the table showed a comfortable pass for a failing class,
      // because the model's CC_CHP over-run (+2.54 TWh) cancelled part of the
      // CC_REGULAR miss. The C1 partition wins: every classFull class gets its
      // own row and the CHP subclasses are shown separately (they are separate
      // C1 rows, and the Fossil-classes table already lists them that way).
      const FG_disp = FG;
      const cf_d = Object.fromEntries(FG.map(g => [g, cf[g] || 0]));
      const gm_d = Object.fromEntries(FG.map(g => [g, gm[g] || 0]));
      // C1's VOLUME band — ±min(max(2% of ISO load, 3% of actual generation),
      // 8 TWh) (the gen-floor is the rubric v3.4 owner amendment 2026-08-18) —
      // the leg that actually fails most often and had no column here at all
      // (only Δpp, the share leg, was shown, so a volume-only breach was
      // invisible whatever the class partition). Mirrors
      // calibration_verdict._fuelmix_vol_band and the page's own volInTol.
      const volBand = Math.min(Math.max(SUM_TOL_LOAD_FRAC * totalLoad(yr), SUM_TOL_GEN_FLOOR_FRAC * aGen), SUM_TOL_LOAD_CAP);

      let h = `<div class="bc-panel"><h2>Generation mix <span class="panel-sub">(system-wide; share of total generation by class vs grid-delivered EIA-923 (923 &minus; BTM); CHP shown separately, as C1 gates it; BTM excluded — grid-delivered only)</span></h2>`;
      h += `<p class="panel-sub">${esc(RUN(yr).label || yearRunId(yr))} generation ${mGen.toFixed(1)} TWh &middot; actual ${aGen.toFixed(1)} TWh`
        + (mImp != null ? ` &middot; + net imports ${mImp.toFixed(1)} (actual ${aImp == null ? '—' : aImp.toFixed(1)}) &rarr; supply ${(mGen + mImp).toFixed(1)} TWh vs load ${load.toFixed(1)} TWh` : '') + `</p>`;
      if (prelim) h += '<p class="panel-sub" style="color:#9a5b12"><b>Preliminary EIA-923 vintage:</b> only <span class="badge-923 ok">&#10003; 923</span> classes are verified-complete and gate the C1 fuel-mix test; <span class="badge-923 inc">&#9888; 923</span> (incomplete) and <span class="badge-923 imm">&mdash; 923</span> (immaterial) classes are shown for reference but not gated.</p>';
      h += `<div class="bc-table-wrap"><table>
        <thead><tr><th>class</th><th>model TWh</th><th>actual TWh</th><th title="C1 volume leg: ±min(max(${(SUM_TOL_LOAD_FRAC * 100).toFixed(1)}% ISO load, ${(SUM_TOL_GEN_FLOOR_FRAC * 100).toFixed(1)}% actual gen), ${SUM_TOL_LOAD_CAP} TWh) = ±${volBand.toFixed(2)} TWh">Δ TWh</th><th>model %gen</th><th>actual %gen</th><th title="C1 share leg: ±${SUM_TOL_SHARE_PP} pp">Δpp</th></tr></thead>
        <tbody>`;

      for (const g of FG_disp) {
        const a = cf_d[g] || 0, m = gm_d[g] || 0;
        const a_g = aGen > 0 ? 100 * a / aGen : 0, m_g = mGen > 0 ? 100 * m / mGen : 0, dpp = m_g - a_g;
        const dtwh = m - a;
        const ci = prelim && (g in ((getCompleteness()?.[yr] || {})[iso] || {})) ? cmpInfo(yr, iso, g) : null;
        const rowcls = ci ? (ci.status === 'incomplete' ? ' class="cmpl-inc"' : (ci.status === 'immaterial' ? ' class="cmpl-imm"' : '')) : '';
        // Colour BOTH C1 legs by C1's own bands, and only where the class
        // actually gates — so a green cell means "inside the gate" and nothing
        // else. Non-gated rows (non-fossil, C1-excluded, incomplete vintage)
        // stay uncoloured rather than borrowing a verdict they never face.
        const gated = classIsGated(yr, g) && !(ci && !ci.gate);
        const dppcls = gated ? (Math.abs(dpp) <= SUM_TOL_SHARE_PP ? 'clr-good' : 'clr-bad') : '';
        const dvcls = gated ? (Math.abs(dtwh) <= volBand ? 'clr-good' : 'clr-bad') : '';
        h += `<tr${rowcls}><td>${esc(mixLabel(g))}${cmpBadge(ci)}</td><td class="num">${m.toFixed(2)}</td><td class="num">${a.toFixed(2)}</td>`
          + `<td class="num ${dvcls}">${fmtSigned2(dtwh)}</td>`
          + `<td class="num">${m_g.toFixed(1)}</td><td class="num">${a_g.toFixed(1)}</td>`
          + `<td class="num ${dppcls}">${fmtpp(dpp)}</td></tr>`;
      }
      h += `<tr class="sub"><td>Total generation</td><td class="num">${mGen.toFixed(2)}</td><td class="num">${aGen.toFixed(2)}</td>`
        + `<td class="num">${fmtSigned2(mGen - aGen)}</td>`
        + `<td class="num">100.0</td><td class="num">100.0</td><td class="num"></td></tr>`;
      h += `<tr><td colspan="7" class="panel-sub" style="text-align:left;white-space:normal;padding:6px 0 0">A class passes C1 iff BOTH legs are inside their band: |Δ TWh| ≤ ±${volBand.toFixed(2)} (=&nbsp;min(max(${(SUM_TOL_LOAD_FRAC * 100).toFixed(1)}%&nbsp;ISO&nbsp;load, ${(SUM_TOL_GEN_FLOOR_FRAC * 100).toFixed(1)}%&nbsp;actual&nbsp;gen), ${SUM_TOL_LOAD_CAP}&nbsp;TWh)) AND |Δpp| ≤ ±${SUM_TOL_SHARE_PP}. Only C1-gated fossil classes are coloured; CHP subclasses are listed separately because C1 scores them separately.</td></tr>`;

      // Reconcile generation + net imports = supply = load.
      if (mImp != null) {
        const mSup = mGen + mImp;
        const aSup = aImp != null ? aGen + aImp : null;
        h += `<tr><td>net imports</td><td class="num">${mImp.toFixed(2)}</td><td class="num">${aImp == null ? '—' : aImp.toFixed(2)}</td><td class="num">${aImp == null ? '' : fmtSigned2(mImp - aImp)}</td><td class="num"></td><td class="num"></td><td class="num"></td></tr>`;
        h += `<tr class="sub"><td>Total supply (gen + net imports)</td><td class="num">${mSup.toFixed(2)}</td><td class="num">${aSup == null ? '—' : aSup.toFixed(2)}</td><td class="num">${aSup == null ? '' : fmtSigned2(mSup - aSup)}</td><td class="num"></td><td class="num"></td><td class="num"></td></tr>`;
        if (load > 0) {
          const dM = mSup - load, dA = aSup != null ? aSup - load : null;
          h += `<tr><td>Load (EIA-930 demand)</td><td class="num">${load.toFixed(2)}</td><td class="num">${load.toFixed(2)}</td><td class="num ${ppcls(100 * dM / load)}">${fmtSigned2(dM)}</td><td class="num"></td><td class="num"></td><td class="num"></td></tr>`;
          if (dA != null && Math.abs(dA) > 2)
            h += `<tr><td colspan="7" class="panel-sub" style="text-align:left;white-space:normal;padding:6px 0 0">Model supply balances load to ${fmtTWh(dM)} (storage round-trip + dump). The actual column is EIA-923 net generation reconciled to the EIA-930 grid series per fossil family (grid-delivered: CHP behind-the-meter and 923↔930 plant-to-BA assignment removed so each family matches what reached the grid). Any residual ${fmtTWh(dA)} vs load is EIA-930's own net-generation-minus-demand discrepancy (the two series are independently surveyed), not behind-the-meter — both columns are now on the same grid-delivered basis, so the per-class shares and the absolute supply total are directly comparable.</td></tr>`;
        }
      }
      return h + '</tbody></table></div></div>';
    }

    function fuelTable(yr) {
      const fr = RUN(yr).fuelRows;
      if (!fr || !fr.length) return '';
      // Gas/coal totals are recomputed from the committed gmModel + bench e930 on
      // the grid-delivered vs raw-EIA-930 basis (user directive 2026-07-02):
      // model = EVERY gas/coal class's grid LP dispatch (the BTM CHP host supply
      // was never in the LP, so the model side is grid-delivered by
      // construction); benchmark = the raw EIA-930 grid series, gas deflated by
      // the biomass/'other' fold-in exactly like calibration_verdict.score_sysvol.
      // Older payloads baked a gas row that dropped the CHP classes from the
      // model and releveled the "930" bench to the EIA-923 classFull basis —
      // that double-showed the CC classification split already visible in the
      // Generation-mix table and made the 930 column a misnomer. r/NRMSE stay
      // the committed payload values (the C4 hourly-shape stats the verdict
      // gates on — a flat level shift does not change r).
      const gm = RUN(yr).gmModel || {}, B = BENCH(yr) || {};
      const e930 = B.e930 || {}, cf = B.classFull || {};
      const hasGm = Object.keys(gm).length > 0;
      let h = `<div class="bc-panel"><h2>Fuel totals vs EIA-930 <span class="panel-sub">(system-wide; 930 not zonal; grid-delivered model vs raw EIA-930 grid series; calibrated fuels only — hydro/oil/other/biomass and the full load reconciliation are in the Generation mix table above)</span></h2>
        <div class="bc-table-wrap"><table>
        <thead><tr><th>fuel</th><th>model TWh</th><th>EIA-930</th><th>Δ</th><th>r</th><th>NRMSE</th></tr></thead>
        <tbody>`;
      for (const f of ['gas', 'coal', 'nuclear', 'wind', 'solar']) {
        const r = fr.find(x => x.fuel === f);
        if (!r) continue;
        let m = r.m, b = r.b;
        if (hasGm && (f === 'gas' || f === 'coal')) {
          const cls = f === 'gas' ? GAS_CLASSES : COAL_CLASSES;
          m = cls.reduce((s, c) => s + (gm[c] || 0), 0);
          if (e930[f] != null) {
            b = e930[f];
            if (f === 'gas' && e930.other != null)
              b -= Math.max(0, (cf.OTHER || 0) + (cf.biomass || 0) - (e930.other || 0));
          }
        }
        const d = b != null && b !== 0 ? 100 * (m - b) / b : null;
        h += `<tr><td>${f}</td><td class="num">${m.toFixed(1)}</td><td class="num">${b == null ? '—' : b.toFixed(1)}</td>
          <td class="num ${d == null ? '' : dcls(d)}">${d == null ? '—' : fmtPctSigned(d)}</td>
          <td class="num">${r.r == null ? '—' : r.r.toFixed(3)}</td>
          <td class="num">${r.nrmse == null ? '—' : r.nrmse.toFixed(3)}</td></tr>`;
      }
      // Net imports
      const ix = fr.find(x => x.fuel === 'interchange');
      if (ix) {
        const m = -ix.m, b = ix.b == null ? null : -ix.b;
        const d = (b != null && b !== 0) ? 100 * (m - b) / b : null;
        h += `<tr><td>net imports</td><td class="num">${m.toFixed(1)}</td><td class="num">${b == null ? '—' : b.toFixed(1)}</td>
          <td class="num ${d == null ? '' : dcls(d)}">${d == null ? '—' : fmtPctSigned(d)}</td>
          <td class="num">${ix.r == null ? '—' : ix.r.toFixed(3)}</td>
          <td class="num">${ix.nrmse == null ? '—' : Math.abs(ix.nrmse).toFixed(3)}</td></tr>`;
      }
      return h + `</tbody></table></div><p class="panel-sub" style="margin-top:6px">Model gas/coal sum every class's grid LP dispatch (behind-the-meter CHP host supply is held out of the LP, so both columns are grid-delivered); EIA-930 gas is deflated by the biomass/&lsquo;other&rsquo; fold-in where the BA folds those fuels into its NG series — the same construction the C2 verdict uses. The per-class split against grid-delivered EIA-923 lives in the Generation mix table.</p></div>`;
    }

    // Fossil classes — model vs full EIA-923 (Δ923), with hourly r and
