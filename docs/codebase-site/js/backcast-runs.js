    function dcls(v, lo, hi) {
      if (v == null || isNaN(v)) return '';
      const a = Math.abs(v);
      return a < (lo ?? SUM_TOL_PCT) ? 'clr-good' : a < (hi ?? 3 * SUM_TOL_PCT) ? 'clr-ok' : 'clr-bad';
    }
    // Generation-share (pp) color band: <1pp good, <3pp ok.
    function ppcls(d) { const a = Math.abs(d); return a < 1 ? 'clr-good' : a < 3 ? 'clr-ok' : 'clr-bad'; }
    function rcls(r) {
      if (r == null) return '';
      return r >= R_GOOD ? 'clr-good' : r >= R_OK ? 'clr-ok' : 'clr-bad';
    }
    // Composite class-capture score: geometric mean of hourly-r, (1−NRMSE) and
    // (1−|volume dev|), ×100. This is the number the deployed dashboard shows
    // as "Class capture" — NOT a volume ratio.
    //
    // THE ONLY IMPLEMENTATION. It used to be defined twice — here and in the
    // Python dashboard shell scripts/probes/_backcast_shell.py — and the
    // comments here still claimed to mirror it. That shell was deleted when
    // the JSON-driven pages replaced it, so there is nothing left to mirror:
    // this function IS capScore. Its scorer-derived inputs (the C1 bands that
    // decide which classes gate) now arrive generated via
    // window.BC.rubricConsts, so the one remaining hand-typed number here is
    // the display cube-root itself, which no verdict criterion reads.
    function capScore(r, nr, dev) { return 100 * Math.cbrt(Math.max(0, r) * Math.max(0, 1 - nr) * Math.max(0, 1 - Math.abs(dev))); }
    // Mean-normalized NRMSE, matching the shell's nrmse(model, actual): the SSE is
    // normalized by the MEAN of the actual (second arg), not by its range. Kept
    // local so it never diverges from the imported (range-normalized) bc-data nrmse.
    function nrmseM(m, o) { let s = 0, om = 0, n = m.length; for (let i = 0; i < n; i++) { s += (m[i] - o[i]) ** 2; om += o[i]; } om /= n; return om > 0 ? Math.sqrt(s / n) / om : 9.9; }
